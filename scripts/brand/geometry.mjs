// Spleen mark geometry. Every drawing is read from the approved identity kit
// in docs/brand/source, so no output can drift from the master SVG.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SOURCE_DIR = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', '..', 'docs', 'brand', 'source');

export const sourceSvg = (name) => fs.readFileSync(path.join(SOURCE_DIR, name), 'utf8');

const attribute = (svg, tag, name) => {
  const element = new RegExp(`<${tag}\\b[^>]*>`).exec(svg)?.[0];
  if (!element) throw new Error(`brand source is missing <${tag}>`);
  const value = new RegExp(`\\s${name}="([^"]+)"`).exec(element)?.[1];
  if (value === undefined) throw new Error(`brand source is missing ${name} on <${tag}>`);
  return value;
};

const allAttributes = (svg, tag, name) => {
  const regex = new RegExp(`<${tag}\\b[^>]*\\s${name}="([^"]+)"`, 'g');
  const values = [];
  let match;
  while ((match = regex.exec(svg)) !== null) {
    values.push(match[1]);
  }
  return values;
};

const appIcon = sourceSvg('spleen-app-icon.svg');
const lightTile = sourceSvg('spleen-light-tile.svg');
const symbol = sourceSvg('spleen-symbol-color-transparent.svg');
const tray = sourceSvg('spleen-tray-white.svg');

const symbolPaths = allAttributes(symbol, 'path', 'd');
const symbolFills = allAttributes(symbol, 'path', 'fill');
if (symbolPaths.length !== 3 || symbolFills.length !== 3) {
  throw new Error('brand source symbol must contain upper, core, and lower paths');
}

export const SPLEEN_UPPER_PATH = symbolPaths[0];
export const SPLEEN_CORE_PATH = symbolPaths[1];
export const SPLEEN_LOWER_PATH = symbolPaths[2];
export const SPLEEN_PATH = SPLEEN_UPPER_PATH;
export const SPLEEN_PATHS = [SPLEEN_UPPER_PATH, SPLEEN_CORE_PATH, SPLEEN_LOWER_PATH];
export const SPLEEN_INK = symbolFills[0];
export const SPLEEN_ACCENT = symbolFills[1];

export const SPLEEN_TILE = {
  x: attribute(appIcon, 'rect', 'x'),
  y: attribute(appIcon, 'rect', 'y'),
  width: attribute(appIcon, 'rect', 'width'),
  height: attribute(appIcon, 'rect', 'height'),
  rx: attribute(appIcon, 'rect', 'rx'),
  fill: attribute(appIcon, 'rect', 'fill'),
  stroke: attribute(appIcon, 'rect', 'stroke'),
  strokeWidth: attribute(appIcon, 'rect', 'stroke-width'),
};

export const SPLEEN_LIGHT_TILE = {
  x: attribute(lightTile, 'rect', 'x'),
  y: attribute(lightTile, 'rect', 'y'),
  width: attribute(lightTile, 'rect', 'width'),
  height: attribute(lightTile, 'rect', 'height'),
  rx: attribute(lightTile, 'rect', 'rx'),
  fill: attribute(lightTile, 'rect', 'fill'),
  stroke: attribute(lightTile, 'rect', 'stroke'),
  strokeWidth: attribute(lightTile, 'rect', 'stroke-width'),
};

const TRAY_TRANSFORM = /<g\b[^>]*\stransform="([^"]+)"/.exec(tray)?.[1];
if (!TRAY_TRANSFORM) throw new Error('brand source is missing the tray transform');

export const FLAT_LOGO = {
  shell: [SPLEEN_UPPER_PATH, SPLEEN_LOWER_PATH],
  core: SPLEEN_CORE_PATH,
};

// Tight viewBox around the mark, for slots that need it to fill the box:
// 24 units of padding around the keystone fold mark (x 240..760, y 156..844).
export const SPLEEN_MARK_VIEWBOX = '216 132 568 736';

// Bounds of the master monogram: x 240..760 (width 520), y 156..844 (height 688),
// centered at (500, 500). Scaled to 21.6 units tall inside a 24-unit icon box.
const MARK_BOX = { left: 240, top: 156, width: 520, height: 688 };
const ICON_SCALE = 0.0314;
const ICON_OFFSET = {
  x: (24 - MARK_BOX.width * ICON_SCALE) / 2 - MARK_BOX.left * ICON_SCALE,
  y: (24 - MARK_BOX.height * ICON_SCALE) / 2 - MARK_BOX.top * ICON_SCALE,
};

const markMarkup = (color, { dot = true, dotColor = SPLEEN_ACCENT } = {}) => (
  `<g fill="${color}">`
  + `<path d="${SPLEEN_UPPER_PATH}"/>`
  + `<path d="${SPLEEN_LOWER_PATH}"/>`
  + '</g>'
  + `<path d="${SPLEEN_CORE_PATH}" fill="${dot ? dotColor : color}"/>`
);

export const flatLogoInner = ({ color = 'currentColor', dot = true } = {}) => markMarkup(color, { dot });

// The mark in a 24-unit icon box: centered and crisp beside 24-grid line icons.
export const glyphInner = () => (
  `<g transform="translate(${ICON_OFFSET.x.toFixed(2)} ${ICON_OFFSET.y.toFixed(2)}) scale(${ICON_SCALE})" fill="currentColor">`
  + `<path d="${SPLEEN_UPPER_PATH}"/>`
  + `<path d="${SPLEEN_CORE_PATH}"/>`
  + `<path d="${SPLEEN_LOWER_PATH}"/>`
  + '</g>'
);

